package com.waqtalabs.auxia.identityaccess.interfaces.rest.resources;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/** Part {@code registration} of the request of a brigadist (A_01, A_02). */
public record BrigadeRegistrationRequest(
    @Schema(example = "Miguel Quispe") @NotBlank @Size(max = 150) String fullName,
    @Schema(example = "987654321") @NotBlank @Size(max = 20) String phone,
    @Schema(description = "Organization as the brigadist writes it", example = "Defensa Civil")
        @NotBlank
        @Size(max = 150)
        String organization,
    @Schema(example = "BRG-ALFA-07") @NotBlank @Pattern(regexp = "[A-Za-z0-9-]{3,30}")
        String brigadeCode,
    @Schema(
            description =
                "Random secret generated by the phone, such as 32 bytes in base64. It is the"
                    + " credential of the account once approved; the phone keeps it.")
        @NotBlank
        @Size(min = 32, max = 64)
        String deviceSecret) {}
