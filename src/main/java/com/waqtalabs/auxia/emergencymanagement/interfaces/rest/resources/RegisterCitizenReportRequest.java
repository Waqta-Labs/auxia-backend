package com.waqtalabs.auxia.emergencymanagement.interfaces.rest.resources;

import com.waqtalabs.auxia.emergencymanagement.domain.model.valueobjects.AccessCondition;
import com.waqtalabs.auxia.emergencymanagement.domain.model.valueobjects.SosCategory;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

public record RegisterCitizenReportRequest(
    @Schema(
            description =
                "Generated by the phone. Sending the same id again returns the stored SOS instead"
                    + " of storing it twice.",
            example = "3f0c8a2e-7b1d-4c5e-9a6f-2d8b4e1c7a90")
        @NotNull
        UUID clientReportId,
    @Schema(description = "Always CITIZEN; the server ignores it", example = "CITIZEN")
        String source,
    @Schema(example = "MEDICAL") @NotNull SosCategory category,
    @Schema(
            description = "In Spanish, for the NLP",
            example = "SOS Médico. Necesitan ayuda 3 niños y 2 heridos. Vía bloqueada.")
        @NotBlank
        @Size(max = 2000)
        String text,
    @Schema(
            description = "When the SOS was sent, in UTC, without zone",
            example = "2026-11-06T14:41:05")
        @NotNull
        LocalDateTime reportedAt,
    @Schema(description = "Where the SOS was sent from; omitted when the phone had no GPS")
        @Valid
        GeolocationResource location,
    @Schema(description = "Optional; none when omitted") @Valid VulnerablePeopleResource people,
    @Schema(description = "Optional; up to the four conditions, without repeating")
        @Size(max = 4)
        List<@NotNull AccessCondition> accessConditions,
    @Schema(description = "clientReportId of the earlier SOS this one adds detail to")
        UUID relatedReportId) {}
