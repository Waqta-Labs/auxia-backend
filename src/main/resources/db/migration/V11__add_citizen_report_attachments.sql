-- Photo and 5-second audio of an SOS (A_04). The phone generates the id of each file, so a retry
-- finds it instead of storing it twice. The file lives in a private container of Azure Blob
-- Storage; only the authority downloads it, it never goes to the public API nor to the
-- blockchain (TS-C02). An SOS has at most one photo and one audio.

CREATE TABLE emergency_management.citizen_report_attachments (
    id                  UUID PRIMARY KEY,
    citizen_report_id   UUID NOT NULL
        REFERENCES emergency_management.citizen_reports (id) ON DELETE RESTRICT,
    type                VARCHAR(5) NOT NULL CHECK (type IN ('PHOTO', 'AUDIO')),
    content_type        VARCHAR(50) NOT NULL,
    size_bytes          BIGINT NOT NULL CHECK (size_bytes > 0),
    storage_url         TEXT NOT NULL,
    received_at         TIMESTAMP NOT NULL,
    CONSTRAINT uq_citizen_report_attachment_type UNIQUE (citizen_report_id, type)
);

COMMENT ON TABLE emergency_management.citizen_report_attachments IS 'Aggregate SosAttachment. Photo or audio of an SOS; its id is generated by the phone.';
