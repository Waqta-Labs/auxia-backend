-- SOS that citizens send from the mobile app without signing in. The phone generates the id
-- (clientReportId), so a retry of the same SOS finds it instead of storing it twice. When the
-- SOS can be placed in an active emergency it also becomes a field report of source CITIZEN,
-- which the authority reviews like any other; field_report_id points to it.

CREATE TABLE emergency_management.citizen_reports (
    id                  UUID PRIMARY KEY,
    category            VARCHAR(10) NOT NULL
        CHECK (category IN ('MEDICAL', 'RESCUE', 'SUPPLIES')),
    text                TEXT NOT NULL,
    reported_at         TIMESTAMP NOT NULL,
    received_at         TIMESTAMP NOT NULL,
    latitude            DOUBLE PRECISION
        CHECK (latitude BETWEEN -90 AND 90),
    longitude           DOUBLE PRECISION
        CHECK (longitude BETWEEN -180 AND 180),
    children            INTEGER NOT NULL CHECK (children >= 0),
    elderly_people      INTEGER NOT NULL CHECK (elderly_people >= 0),
    injured_people      INTEGER NOT NULL CHECK (injured_people >= 0),
    access_conditions   JSONB NOT NULL,
    related_report_id   UUID,
    field_report_id     UUID
        REFERENCES emergency_management.field_reports (id) ON DELETE RESTRICT,
    CONSTRAINT chk_citizen_report_location
        CHECK ((latitude IS NULL) = (longitude IS NULL))
);

COMMENT ON TABLE emergency_management.citizen_reports IS 'Aggregate CitizenReport. An SOS of a citizen; its id is the clientReportId generated by the phone. field_report_id is NULL when no active emergency could be found for it.';
COMMENT ON COLUMN emergency_management.citizen_reports.related_report_id IS 'SOS that this one adds detail to. Not a foreign key: the phone may send them in any order.';
